package com.recon.service;

import static org.assertj.core.api.Assertions.assertThat;
import static org.awaitility.Awaitility.await;

import com.recon.core.tolerance.ToleranceConfig;
import com.recon.datagen.DataGenerator;
import com.recon.datagen.DatagenConfig;
import com.recon.datagen.output.CsvDatasetWriter;
import com.recon.service.run.RunStatus;
import com.recon.service.run.RunView;
import java.io.IOException;
import java.io.Reader;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.time.LocalDate;
import java.util.Properties;
import org.junit.jupiter.api.BeforeEach;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.actuate.observability.AutoConfigureObservability;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.client.TestRestTemplate;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.testcontainers.containers.PostgreSQLContainer;

/**
 * Base for integration tests: a real PostgreSQL 16 in a container, Flyway-migrated, and a
 * 2,000-trade dataset generated by recon-datagen (seed 42).
 *
 * <p>The container is a singleton started once per JVM, and Spring caches the context, so all
 * test classes share one database. Each test starts from empty tables.
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
// Spring Boot tests switch metrics exporters off by default; the Prometheus endpoint is under test.
@AutoConfigureObservability
public abstract class IntegrationTest {

    protected static final LocalDate BUSINESS_DATE = DatagenConfig.DEFAULT_START_DATE;
    protected static final int TRADES = 2_000;

    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:16-alpine");
    protected static final Path DATASET;

    static {
        POSTGRES.start();
        DATASET = generateDataset();
    }

    @DynamicPropertySource
    static void properties(DynamicPropertyRegistry registry) {
        registry.add("spring.datasource.url", POSTGRES::getJdbcUrl);
        registry.add("spring.datasource.username", POSTGRES::getUsername);
        registry.add("spring.datasource.password", POSTGRES::getPassword);
        registry.add("recon.import-directory", DATASET::toString);
    }

    @Autowired
    protected TestRestTemplate rest;

    @Autowired
    protected JdbcTemplate jdbc;

    @BeforeEach
    void emptyDatabase() {
        jdbc.execute("""
                truncate recon_break, match_link, recon_run, internal_trade, external_confirm,
                         counterparty_alias, counterparty, instrument restart identity cascade""");
    }

    protected void importDataset() {
        ResponseEntity<String> response = rest.postForEntity("/api/imports", null, String.class);
        assertThat(response.getStatusCode()).as(response.getBody()).isEqualTo(HttpStatus.OK);
    }

    /** Starts a run and polls until it's no longer RUNNING. */
    protected RunView runAndWait(LocalDate businessDate) {
        ResponseEntity<RunView> started = rest.postForEntity("/api/runs?businessDate=" + businessDate, null, RunView.class);
        assertThat(started.getStatusCode()).isEqualTo(HttpStatus.ACCEPTED);
        long id = started.getBody().id();
        RunView[] finished = new RunView[1];
        await().atMost(Duration.ofSeconds(60)).pollInterval(Duration.ofMillis(100)).until(() -> {
            finished[0] = rest.getForObject("/api/runs/" + id, RunView.class);
            return finished[0].status() != RunStatus.RUNNING;
        });
        assertThat(finished[0].status()).as(finished[0].error()).isEqualTo(RunStatus.COMPLETED);
        return finished[0];
    }

    private static Path generateDataset() {
        try {
            Path dir = Files.createTempDirectory("recon-it-dataset");
            Properties properties = new Properties();
            Path tolerances = Path.of(System.getProperty("recon.rootDir", ".."), "config", "tolerances.properties");
            try (Reader reader = Files.newBufferedReader(tolerances)) {
                properties.load(reader);
            }
            DatagenConfig config = DatagenConfig.builder().tradesPerDay(TRADES).seed(42).build();
            try (CsvDatasetWriter writer = new CsvDatasetWriter(dir, false)) {
                new DataGenerator(config, ToleranceConfig.fromProperties(properties)).generate(writer);
            }
            return dir;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
